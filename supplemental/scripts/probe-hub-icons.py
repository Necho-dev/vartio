#!/usr/bin/env python3
"""Generate cmd/probe-hub/web/modules/icons.js from lucide-static (https://lucide.dev, ISC).

  python3 scripts/probe-hub-icons.py              # fetch lucide-static via npm pack
  python3 scripts/probe-hub-icons.py DIR          # use an extracted package/icons dir
  python3 scripts/probe-hub-icons.py --svg NAME   # print markup for static HTML (index.html)

Add a name to ICONS and rerun to make it available as icon("name").
"""
import json
import pathlib
import re
import subprocess
import sys
import tarfile
import tempfile

ICONS = [
    # chrome
    "activity", "search", "moon", "log-out", "maximize", "minimize", "x", "arrow-left", "pencil",
    # host actions
    "square-terminal", "monitor", "list", "folder-open", "trash-2", "arrow-right-left",
    # file manager
    "chevron-left", "chevron-right", "arrow-up", "arrow-down", "arrow-up-down", "house", "refresh-cw",
    "folder-plus", "upload", "folder-up", "download", "pencil-line", "trash", "plus", "rotate-ccw",
    "triangle-alert", "folder", "file", "file-text", "file-image", "file-archive",
    # events
    "network", "package", "user", "copy", "check", "circle-arrow-up",
    # plugins
    "grid-2x2-plus", "globe", "play", "send", "external-link", "camera",
]

TEMPLATE = """// @ts-check
// Generated by scripts/probe-hub-icons.py from lucide-static @VERSION@. Do not edit.
// Lucide icons: ISC License, Copyright (c) Lucide Icons and Contributors.

const PATHS = {
@ROWS@,
};

/** @typedef {keyof typeof PATHS} IconName */

/**
 * Inline SVG markup; size and stroke come from the .i rule in app.css.
 * @param {IconName} name
 * @param {string} [cls]
 */
export const icon = (name, cls = "") => `<svg class="i${cls ? " " + cls : ""}" viewBox="0 0 24 24" aria-hidden="true">${PATHS[name]}</svg>`;
"""

OUT = pathlib.Path(__file__).resolve().parent.parent / "cmd/probe-hub/web/modules/icons.js"


def fetch():
    tmp = pathlib.Path(tempfile.mkdtemp())
    name = subprocess.check_output(["npm", "pack", "lucide-static@latest", "--silent"], cwd=tmp, text=True).strip().splitlines()[-1]
    with tarfile.open(tmp / name) as t:
        t.extractall(tmp, filter="data")
    return tmp / "package/icons", json.loads((tmp / "package/package.json").read_text())["version"]


def inner(path):
    svg = re.sub(r"<!--.*?-->", "", path.read_text(), flags=re.S)
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    return re.sub(r"\s+", " ", re.sub(r">\s+<", "><", body)).strip()


def main():
    args = sys.argv[1:]
    if args[:1] == ["--svg"]:
        src, _ = fetch()
        for n in args[1:]:
            print(f'<svg class="i" viewBox="0 0 24 24" aria-hidden="true">{inner(src / f"{n}.svg")}</svg>')
        return
    if args:
        src = pathlib.Path(args[0])
        version = json.loads((src.parent / "package.json").read_text())["version"]
    else:
        src, version = fetch()
    rows = ",\n".join(f'  "{n}": `{inner(src / f"{n}.svg")}`' for n in ICONS)
    OUT.write_text(TEMPLATE.replace("@VERSION@", version).replace("@ROWS@", rows))
    print(f"wrote {OUT} ({len(ICONS)} icons, lucide-static {version})")


main()
